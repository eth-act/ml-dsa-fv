IT={it:(pa,pb) for it,st,path,pa,pb,c in iters()}
COST={it:c for it,st,path,pa,pb,c in iters()}
def rounds(its, abp, flp, h, M0="m"):
    L=[]; prev=M0; hi="hI0"
    for n,it in enumerate(its):
        Mn=f"M{it+1}"
        L.append(f"""  obtain ⟨{Mn}, hI{it+1}, hR{it}⟩ := rnd {it}
    (iter{it} hs (rest := wd ret :: tail) (by simp only [List.length_cons]; omega)
      U5 U4 U3 U2 U1 U0 {h} {flp} {abp} {prev} (by omega) (by omega))
    hg (by norm_num) (by norm_num) {hi} (by simp [ldw, complemented]) (by simp [ldw, complemented])
    (by simp [ldw, complemented]) (by norm_num) (by norm_num)""")
        prev=Mn; hi=f"hI{it+1}"
    return "\n".join(L), prev
