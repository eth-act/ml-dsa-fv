def mnemonic(code: bytes, pc: int) -> str:
    o = code[pc]
    if 0x5F <= o <= 0x7F:
        w = o - 0x5F
        if w == 0:
            return "PUSH0"
        return f"PUSH{w} 0x{code[pc + 1:pc + 1 + w].hex()}"
    if 0x80 <= o <= 0x8F:
        return f"DUP{o - 0x7F}"
    if 0x90 <= o <= 0x9F:
        return f"SWAP{o - 0x8F}"
    for t in (ARITH, COMP, ENV, SMF, SYS):
        if o in t:
            return t[o]
    return f"0x{o:02x}"


