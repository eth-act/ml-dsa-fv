#!/usr/bin/env python3
"""Emit the proof-facing artifact modules for a frozen hand-written bytecode.

Usage:
  python3 scripts/proofgen_artifact.py HEX NS DIR TACTIC MEMWORDS

e.g.  python3 scripts/proofgen_artifact.py MlDsaOpt/44/opt.hex MlDsaOpt44 MlDsaOpt44 opt44 2065

Writes, for namespace NS (proof namespace NS.Proofs) under directory DIR:

* DIR/Bytecode.lean     `NS.optBytecode`, the reducible byte literal of HEX;
* DIR/Artifact.lean     the instruction list (disassembled from HEX; every
                        byte is an instruction, PUSH immediates included), its
                        assembly equation (`rfl`), the well-formedness
                        certificate and `located` / `locatedPath`;
* DIR/Infra/Ctx.lean    `Ctx` / `Ctx0` (running facts about states of this
                        code; `memWords` = MEMWORDS is the fixed memory size),
                        `RetOK`;
* DIR/Infra/Code.lean   lookup trees validated once by the kernel, `instrAt`,
                        `pcAt`, `jumpdest_of`, the simprocs;
* DIR/Infra/Block.lean  `stepL_located` and the tactic `TACTIC_block`;
* DIR/Infra/Reach.lean  `reach_block`, `reach_block_pot`, `reach_mcopy`,
                        `RetOK.callee`, `blockCostEval` and `TACTIC_reach`;
* DIR/Infra/Reflect.lean kernel-checked reflective reach, with chunked fallback;
* DIR/Infra.lean        umbrella import.

The templates are artifact-independent; the artifact-independent lemmas live
in `MlDsaOptCommon`. Nothing here depends on how the bytes were produced.
"""
