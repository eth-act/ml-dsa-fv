ARITH = {0x00: "STOP", 0x01: "ADD", 0x02: "MUL", 0x03: "SUB", 0x04: "DIV", 0x05: "SDIV",
         0x06: "MOD", 0x07: "SMOD", 0x08: "ADDMOD", 0x09: "MULMOD", 0x0A: "EXP",
         0x0B: "SIGNEXTEND"}
COMP = {0x10: "LT", 0x11: "GT", 0x12: "SLT", 0x13: "SGT", 0x14: "EQ", 0x15: "ISZERO",
        0x16: "AND", 0x17: "OR", 0x18: "XOR", 0x19: "NOT", 0x1A: "BYTE", 0x1B: "SHL",
        0x1C: "SHR", 0x1D: "SAR", 0x1E: "CLZ"}
ENV = {0x35: "CALLDATALOAD", 0x36: "CALLDATASIZE", 0x37: "CALLDATACOPY"}
SMF = {0x50: "POP", 0x51: "MLOAD", 0x52: "MSTORE", 0x53: "MSTORE8", 0x56: "JUMP",
       0x57: "JUMPI", 0x5B: "JUMPDEST", 0x5E: "MCOPY"}
SYS = {0xF3: "RETURN", 0xFD: "REVERT", 0xFE: "INVALID"}


def op_expr(o: int) -> str:
    E = "EvmSemantics.Operation"
    if o in ARITH:
        return f"{E}.StopArith ({E}.StopArithOps.{ARITH[o]})"
    if o in COMP:
        return f"{E}.CompBit ({E}.CompareBitwiseOps.{COMP[o]})"
    if o in ENV:
        return f"{E}.Env ({E}.EnvOps.{ENV[o]})"
    if o in SMF:
        return f"{E}.StackMemFlow ({E}.StackMemFlowOps.{SMF[o]})"
    if o in SYS:
        return f"{E}.System ({E}.SystemOps.{SYS[o]})"
    if 0x80 <= o <= 0x8F:
        return f"{E}.Dup {{ idx := {o - 0x80} }}"
    if 0x90 <= o <= 0x9F:
        return f"{E}.Swap {{ idx := {o - 0x90} }}"
    raise SystemExit(f"unsupported opcode 0x{o:02x}")


def disassemble(code: bytes):
    """(pc, lean expr, is_jumpdest) for every instruction."""
    out = []
    i = 0
    while i < len(code):
        o = code[i]
        if 0x5F <= o <= 0x7F:
            w = o - 0x5F
            imm = code[i + 1:i + 1 + w]
            if len(imm) != w:
                raise SystemExit(f"truncated PUSH at {i}")
            v = int.from_bytes(imm, "big")
            out.append((i, f"YulEvmCompiler.Instr.push {w} {v}", False))
            i += 1 + w
        else:
            out.append((i, f"YulEvmCompiler.Instr.op ({op_expr(o)})", o == 0x5B))
            i += 1
    return out


def sub(t: str, d: dict) -> str:
    for k, v in d.items():
        t = t.replace(f"@{k}@", str(v))
    return t


