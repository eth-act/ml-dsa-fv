EIP8024 = {0xE6: "dupN", 0xE7: "swapN", 0xE8: "exchange"}


def disassemble(code: bytes):
    """(pc, lean expr, is_jumpdest) for every instruction."""
    out = []
    i = 0
    while i < len(code):
        o = code[i]
        if 0x5F <= o <= 0x7F:
            w = o - 0x5F
            imm = code[i + 1:i + 1 + w]
            if len(imm) != w:
                raise SystemExit(f"truncated PUSH at {i}")
            v = int.from_bytes(imm, "big")
            out.append((i, f"EvmProof.XInstr.base (YulEvmCompiler.Instr.push {w} {v})", False))
            i += 1 + w
        elif o in EIP8024:
            if i + 1 >= len(code):
                raise SystemExit(f"truncated EIP-8024 immediate at {i}")
            out.append((i, f"EvmProof.XInstr.{EIP8024[o]} {code[i + 1]}", False))
            i += 2
        else:
            out.append((i, f"EvmProof.XInstr.base (YulEvmCompiler.Instr.op ({pa.op_expr(o)}))",
                        o == 0x5B))
            i += 1
    return out


def mnemonic(code: bytes, pc: int) -> str:
    o = code[pc]
    if o in EIP8024:
        return f"{EIP8024[o].upper()} 0x{code[pc + 1]:02x}"
    return pa.mnemonic(code, pc)


def rep(t: str, pairs) -> str:
    for a, b in pairs:
        if a not in t:
            raise SystemExit(f"template substitution not found: {a[:60]!r}")
        t = t.replace(a, b)
    return t


