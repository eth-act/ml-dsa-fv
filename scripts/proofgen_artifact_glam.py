def main(argv):
    if len(argv) != 5:
        raise SystemExit(__doc__)
    hexpath, ns, outdir, tac, memw = argv
    code = bytes.fromhex(open(hexpath).read().strip())
    instrs = disassemble(code)
    n = len(instrs)
    P = f"{ns}.Proofs"
    os.makedirs(os.path.join(outdir, "Infra"), exist_ok=True)
    d = dict(NS=ns, P=P, HEX=hexpath, SIZE=len(code), N=n, TAC=tac, MEMW=memw)
    CI = pa.CHUNK_INSTRS
    ich = [instrs[i:i + CI] for i in range(0, n, CI)]
    d["NCH"] = len(ich)
    d["CI"] = CI
    bounds = [c[0][0] for c in ich] + [len(code)]
    ctext = ""
    for k in range(len(ich)):
        body = ", ".join(f"0x{b:02x}" for b in code[bounds[k]:bounds[k + 1]])
        ctext += f"def optChunk{k} : List UInt8 := [{body}]\n\n"
    with open(os.path.join(outdir, "Bytecode.lean"), "w") as f:
        f.write(pa.sub(BYTECODE, dict(d, CHUNKS=ctext,
                                      SUM=" ++ ".join(f"optChunk{k}" for k in range(len(ich))))))
    with open(os.path.join(outdir, "Artifact.lean"), "w") as f:
        f.write(pa.sub(ARTIFACT_HEAD, d))
        for k, c in enumerate(ich):
            body = ",\n ".join(e for _, e, _ in c)
            f.write(f"def instructions{k} : List XInstr :=\n[{body}]\n\n")
            f.write(f"theorem instructions{k}_length : instructions{k}.length = {len(c)} := by rfl\n\n")
            f.write(f"theorem assembleBytes_instructions{k} :\n    xassembleBytes instructions{k} = {ns}.optChunk{k} := by rfl\n\n")
            f.write(f"theorem allWellFormedB_instructions{k} :\n    instructions{k}.all (EvmProof.Stepper.xwellFormedB .Amsterdam) = true := by rfl\n\n")
        r = range(len(ich))
        f.write(pa.sub(ARTIFACT_TAIL, dict(d, SUM=" ++ ".join(f"instructions{k}" for k in r),
                                           LENS=", ".join(f"instructions{k}_length" for k in r),
                                           ASMS=", ".join(f"assembleBytes_instructions{k}" for k in r),
                                           WFS=", ".join(f"allWellFormedB_instructions{k}" for k in r),
                                           LENAPP=", ".join(["List.length_append"] * (len(ich) - 1)),
                                           ASMAPP=", ".join(["xassembleBytes_append"] * (len(ich) - 1)),
                                           ALLAPP=", ".join(["List.all_append"] * (len(ich) - 1)))))
    groups = [list(range(g, min(g + pa.CHUNKS_PER_CHECK, len(ich))))
              for g in range(0, len(ich), pa.CHUNKS_PER_CHECK)]
    for gi, g in enumerate(groups):
        okg = ""
        for k in g:
            okg += (f"theorem tables_ok{k} : checkAll instrTree pcTree {k * CI} {bounds[k]} "
                    f"instructions{k} = true := by\n  decide +kernel\n\n"
                    f"theorem size_instructions{k} : (instructions{k}.map isz).sum = "
                    f"{bounds[k + 1] - bounds[k]} := by\n  decide +kernel\n\n")
        with open(os.path.join(outdir, "Infra", f"TablesOk{gi}.lean"), "w") as f:
            f.write(pa.sub(TABLES_OK, dict(d, CHUNKOK=okg, FROM=g[0], TO=g[-1])))
    chunkok = ""
    for k in range(1, len(ich)):
        pre = " ++ ".join(f"instructions{j}" for j in range(k))
        prek = pre + f" ++ instructions{k}"
        prevlen = f"prefix_length{k - 1}" if k > 1 else "instructions0_length"
        prevsize = f"prefix_size{k - 1}" if k > 1 else "size_instructions0"
        prevok = f"prefix_ok{k - 1}" if k > 1 else "tables_ok0"
        chunkok += (f"theorem prefix_length{k} : ({prek}).length = {CI * k + len(ich[k])} := by\n"
                    f"  rewrite [List.length_append, {prevlen}, instructions{k}_length]\n  rfl\n\n"
                    f"theorem prefix_size{k} : (({prek}).map isz).sum = {bounds[k + 1]} := by\n"
                    f"  rewrite [List.map_append, List.sum_append, {prevsize}, size_instructions{k}]\n  rfl\n\n"
                    f"theorem prefix_ok{k} : checkAll instrTree pcTree 0 0 ({prek}) = true :=\n"
                    f"  checkAll_append _ _ _ _ _ _ {prevok}\n"
                    f"    (by rewrite [{prevlen}, {prevsize}]; exact tables_ok{k})\n\n")
    d2 = dict(d, CHUNKOK=chunkok, APPLY=f"exact prefix_ok{len(ich) - 1}",
              IMPORTS="\n".join(f"import {ns}.Infra.TablesOk{gi}" for gi in range(len(groups))))
    for name, t in (("Ctx", CTX), ("Tables", TABLES), ("Code", CODE), ("Block", BLOCK),
                    ("Reach", REACH), ("Reflect", REFLECT)):
        with open(os.path.join(outdir, "Infra", name + ".lean"), "w") as f:
            f.write(pa.sub(t, d2))
    with open(os.path.join(outdir, "Infra.lean"), "w") as f:
        f.write(pa.sub(UMBRELLA, d))
    with open(os.path.join(outdir, "listing.tsv"), "w") as f:
        f.write("index\tpc\tinstr\n")
        for k, (pc, e, _) in enumerate(instrs):
            f.write(f"{k}\t{pc}\t{mnemonic(code, pc)}\n")
    print(f"{ns}: {len(code)} bytes, {n} instructions, {len(ich)} chunks")


if __name__ == "__main__":
    main(sys.argv[1:])
