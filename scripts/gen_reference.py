def main():
    rcinit = [f"    mstore({h(RC + 32 * i)}, {h(v)})" for i, v in enumerate(RC_VALUES)]
    subst = {
        "@ROUND@": indent(keccak_round(ST, BT, "r") + keccak_round(BT, ST, "add(r, 1)"), 12),
        "@RCINIT@": "\n".join(rcinit),
        "@QM2@": str(Q - 2),
        "@Q@": str(Q),
    }
    for name in ["ST", "BT", "RC", "ZETA", "ZH", "CH", "AP", "ACC", "TP", "HB", "XOF",
                 "SEEDA", "SEEDC", "PADB", "W1", "PK", "MSGIN"]:
        subst[f"@{name}@"] = h(globals()[name])
    text = TEMPLATE
    for key in sorted(subst, key=len, reverse=True):
        text = text.replace(key, subst[key])
    assert "@" not in text, "unsubstituted placeholder"
    print(text, end="")


if __name__ == "__main__":
    main()
