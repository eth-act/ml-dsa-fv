#!/usr/bin/env python3
"""Generate the proof-friendly reference Yul for ML-DSA-44, -65 or -87.

The ML-DSA-44 reference (scripts/gen_reference.py) is turned into a template
by replacing every parameter-set-dependent fragment with a placeholder; the
`SLOTS` table below is therefore the complete list of differences between the
three verifiers. Everything else (Keccak, SHAKE, NTT, NTT^-1, RejNTTPoly,
the bounded SampleInBall scan, unpacking, the memory-map discipline) is the
ML-DSA-44 code unchanged. For NN = 44 the output is byte-identical to
MlDsa44/Reference/reference.yul.

Usage: python3 scripts/gen_reference_param.py NN > MlDsaNN/Reference/reference.yul
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_reference as g44  # noqa: E402

Q = g44.Q
POLY = g44.POLY

# FIPS 204 Table 1: k, l, eta, tau, lambda, gamma1, gamma2, omega.
PARAMS = {
    44: (4, 4, 2, 39, 128, 2 ** 17, (Q - 1) // 88, 80),
    65: (6, 5, 4, 49, 192, 2 ** 19, (Q - 1) // 32, 55),
    87: (8, 7, 2, 60, 256, 2 ** 19, (Q - 1) // 32, 75),
}


def bitlen(x):
    return x.bit_length()


def roundup(x, m):
    return (x + m - 1) // m * m


class Set:
    def __init__(self, nn):
        self.nn = nn
        (self.k, self.l, eta, self.tau, lam, self.gamma1, self.gamma2,
         self.omega) = PARAMS[nn]
        self.beta = self.tau * eta
        self.clen = lam // 4
        self.zbits = bitlen(self.gamma1 - 1) + 1
        self.zlen = 32 * self.zbits
        self.pk_len = 32 + 32 * self.k * (bitlen(Q - 1) - 13)
        self.sig_len = self.clen + self.l * self.zlen + self.omega + self.k
        self.m = (Q - 1) // (2 * self.gamma2)
        self.w1bits = bitlen(self.m - 1)
        self.group_bytes = 4 * self.w1bits // 8   # bytes per 4 coefficients
        assert 4 * self.w1bits % 8 == 0
        self.row_bytes = 32 * self.w1bits
        self.w1len = 64 + self.k * self.row_bytes

        # Memory map (byte offsets); ST..ZETA as in ML-DSA-44.
        self.ZH = g44.ZETA + POLY            # z-hat[0..l-1]
        self.CH = self.ZH + self.l * POLY    # c-hat
        self.AP = self.CH + POLY             # current A[i][j]
        self.ACC = self.AP + POLY            # row accumulator
        self.TP = self.ACC + POLY            # t1[i] * 2^d, then its NTT
        self.HB = self.TP + POLY             # hint bits, k * 256 bytes
        self.XOF = self.HB + self.k * 0x100  # squeeze buffer, 1008 + 24 bytes
        self.SEEDA = self.XOF + 0x420        # rho || s || r, 34 bytes
        self.SEEDC = self.SEEDA + 0x40       # c-tilde, lambda/4 <= 64 bytes
        self.PADB = self.SEEDC + 0x40        # final padded sponge block
        self.W1 = self.PADB + 0xC0           # mu (64) || w1Encode
        self.PK = self.W1 + roundup(self.w1len, 0x40)       # public key copy
        self.MSGIN = self.PK + roundup(self.pk_len, 0x40)   # tr || 0 || 0 || M
        assert self.clen <= 0x40 and self.w1len >= 160 and self.tau <= 64
        if nn == 44:
            for name in ["ZH", "CH", "AP", "ACC", "TP", "HB", "XOF", "SEEDA", "SEEDC",
                         "PADB", "W1", "PK", "MSGIN"]:
                assert getattr(self, name) == getattr(g44, name), name


def w1_stores(s):
    out = []
    for b in range(s.group_bytes):
        last = b == s.group_bytes - 1
        v = "v" if b == 0 else f"shr({8 * b}, v)"
        e = v if last and b > 0 else f"and({v}, 0xff)"
        dst = "o" if b == 0 else f"add(o, {b})"
        out.append(f"            mstore8({dst}, {e})")
    return "\n".join(out)


def ctilde_check(s):
    out = []
    for w in range(0, s.clen, 32):
        n = min(32, s.clen - w)
        mem, cd = f"mload({g44.h(s.XOF + w)})", f"calldataload({s.pk_len + w})"
        if n < 32:
            mem, cd = f"shr({8 * (32 - n)}, {mem})", f"shr({8 * (32 - n)}, {cd})"
        out.append(f"    ok := and(ok, eq({mem}, {cd}))")
    return "\n".join(out)


# (fragment of the ML-DSA-44 template, its placeholder form, occurrences).
SLOTS = [
    ("// GENERATED by scripts/gen_reference.py; do not edit.", "@GENERATED@", 1),
    ("ML-DSA-44", "ML-DSA-@NN@", 1),
    ("    ok := and(ok, eq(mload(@XOF@), calldataload(1312)))\n", "@CCHECK@\n", 1),
    ("            mstore8(o, and(v, 0xff))\n"
     "            mstore8(add(o, 1), and(shr(8, v), 0xff))\n"
     "            mstore8(add(o, 2), shr(16, v))", "@W1STORES@", 1),
    ("calldatacopy(@SEEDC@, 1312, 32)", "calldatacopy(@SEEDC@, @PKLEN@, @CLEN@)", 1),
    ("shake(136, @SEEDC@, 32, @XOF@, 2)", "shake(136, @SEEDC@, @CLEN@, @XOF@, 2)", 1),
    ("3732", "@CDMIN@", 3),
    ("1312", "@PKLEN@", 3),
    ("2420", "@SIGLEN@", 1),
    ("//   @ZH@  z-hat[0..3]", "//   @ZH@  z-hat[0..@LM1@]", 1),
    # HintBitUnpack
    ("for { let i := 0 } lt(i, 32) { i := add(i, 1) } { mstore(add(@HB@",
     "for { let i := 0 } lt(i, @HBWORDS@) { i := add(i, 1) } { mstore(add(@HB@", 1),
    ("for { let i := 0 } lt(i, 4) { i := add(i, 1) } {\n"
     "            let bound := byte(0, calldataload(add(3728, i)))",
     "for { let i := 0 } lt(i, @K@) { i := add(i, 1) } {\n"
     "            let bound := byte(0, calldataload(add(@COUNTOFF@, i)))", 1),
    ("gt(bound, 80)", "gt(bound, @OMEGA@)", 1),
    ("lt(idx, 80)", "lt(idx, @OMEGA@)", 1),
    ("add(3648, idx)", "add(@HINTOFF@, idx)", 2),
    ("add(3647, idx)", "add(@HINTPREV@, idx)", 1),
    # z decoding
    ("gamma1 = 2^17", "gamma1 = 2^@G1LOG@", 1),
    ("for { let i := 0 } lt(i, 4) { i := add(i, 1) } {\n"
     "            let base", "for { let i := 0 } lt(i, @L@) { i := add(i, 1) } {\n"
     "            let base", 1),
    ("unpack(add(1344, mul(576, i)), j, 18)", "unpack(add(@ZOFF@, mul(@ZLEN@, i)), j, @ZBITS@)", 1),
    ("and(gt(raw, 78), lt(raw, 262066))", "and(gt(raw, @BETA@), lt(raw, @ZHI@))", 1),
    ("addmod(131072, sub(", "addmod(@GAMMA1@, sub(", 1),
    # UseHint
    ("190464", "@TWOG2@", 3),
    ("gt(r0u, 95232)", "gt(r0u, @G2@)", 1),
    ("mod(add(r1, 1), 44)", "mod(add(r1, 1), @M@)", 1),
    ("mod(add(r1, 43), 44)", "mod(add(r1, @MM1@), @M@)", 1),
    # w1Encode
    ("W1 + 64 + 192 i", "W1 + 64 + @ROWBYTES@ i", 1),
    ("add(64, mul(192, i))", "add(64, mul(@ROWBYTES@, i))", 1),
    ("shl(mul(6, e), w)", "shl(mul(@W1BITS@, e), w)", 1),
    ("let o := add(out, mul(3, g))", "let o := add(out, mul(@GROUPBYTES@, g))", 1),
    # ExpandA row, rows loop, final hash
    ("for { let j := 0 } lt(j, 4)", "for { let j := 0 } lt(j, @L@)", 1),
    ("for { let i := 0 } lt(i, 4) { i := add(i, 1) } {\n"
     "        ok := and(ok, computeRow(i))", "for { let i := 0 } lt(i, @K@) { i := add(i, 1) } {\n"
     "        ok := and(ok, computeRow(i))", 1),
    ("shake(136, @W1@, 832, @XOF@, 1)", "shake(136, @W1@, @W1LEN@, @XOF@, 1)", 1),
    # SampleInBall
    ("let i := 217", "let i := @TAUSTART@", 1),
    ("sub(i, 217)", "sub(i, @TAUSTART@)", 1),
]


def template():
    text = g44.TEMPLATE
    for old, new, count in SLOTS:
        assert text.count(old) == count, (old, text.count(old))
        text = text.replace(old, new)
    # No ML-DSA-44 constant may survive outside the slots above.
    for const in ["1312", "2420", "3732", "3728", "3648", "3647", "1344", "576",
                  "262066", "190464", "95232", "131072", "217", "832", "44)"]:
        assert const not in text, const
    return text


def generate(nn):
    s = Set(nn)
    subst = {
        "@GENERATED@": ("// GENERATED by scripts/gen_reference.py; do not edit." if nn == 44 else
                        f"// GENERATED by scripts/gen_reference_param.py {nn}; do not edit."),
        "@NN@": str(nn),
        "@CCHECK@": ctilde_check(s),
        "@W1STORES@": w1_stores(s),
        "@CDMIN@": str(s.pk_len + s.sig_len),
        "@PKLEN@": str(s.pk_len),
        "@SIGLEN@": str(s.sig_len),
        "@CLEN@": str(s.clen),
        "@LM1@": str(s.l - 1),
        "@HBWORDS@": str(s.k * 8),
        "@K@": str(s.k),
        "@L@": str(s.l),
        "@COUNTOFF@": str(s.pk_len + s.sig_len - s.k),
        "@OMEGA@": str(s.omega),
        "@HINTOFF@": str(s.pk_len + s.sig_len - s.k - s.omega),
        "@HINTPREV@": str(s.pk_len + s.sig_len - s.k - s.omega - 1),
        "@G1LOG@": str(s.gamma1.bit_length() - 1),
        "@ZOFF@": str(s.pk_len + s.clen),
        "@ZLEN@": str(s.zlen),
        "@ZBITS@": str(s.zbits),
        "@BETA@": str(s.beta),
        "@ZHI@": str(2 * s.gamma1 - s.beta),
        "@GAMMA1@": str(s.gamma1),
        "@TWOG2@": str(2 * s.gamma2),
        "@G2@": str(s.gamma2),
        "@M@": str(s.m),
        "@MM1@": str(s.m - 1),
        "@ROWBYTES@": str(s.row_bytes),
        "@W1BITS@": str(s.w1bits),
        "@GROUPBYTES@": str(s.group_bytes),
        "@W1LEN@": str(s.w1len),
        "@TAUSTART@": str(256 - s.tau),
        "@ROUND@": g44.indent(g44.keccak_round(g44.ST, g44.BT, "r")
                              + g44.keccak_round(g44.BT, g44.ST, "add(r, 1)"), 12),
        "@RCINIT@": "\n".join(f"    mstore({g44.h(g44.RC + 32 * i)}, {g44.h(v)})"
                              for i, v in enumerate(g44.RC_VALUES)),
        "@QM2@": str(Q - 2),
        "@Q@": str(Q),
    }
    for name in ["ST", "BT", "RC", "ZETA"]:
        subst[f"@{name}@"] = g44.h(getattr(g44, name))
    for name in ["ZH", "CH", "AP", "ACC", "TP", "HB", "XOF", "SEEDA", "SEEDC", "PADB", "W1",
                 "PK", "MSGIN"]:
        subst[f"@{name}@"] = g44.h(getattr(s, name))
    # Placeholders are substituted in one pass, longest name first; values
    # never contain '@', so no placeholder is introduced by a substitution.
    text = template()
    for key in sorted(subst, key=len, reverse=True):
        text = text.replace(key, subst[key])
    assert "@" not in text, "unsubstituted placeholder"
    return text


def main():
    print(generate(int(sys.argv[1])), end="")


if __name__ == "__main__":
    main()
