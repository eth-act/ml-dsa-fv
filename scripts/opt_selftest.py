#!/usr/bin/env python3
"""Self-tests for the optimised verifier generator (scripts/gen_opt.py).

  python3 scripts/opt_selftest.py [quick]

1. Python FIPS 204 model (opt_ref.verify_model) vs every vector of
   vectors/calldata.txt and vectors/mldsa{65,87}/calldata.txt.
2. Keccak-f kernels (kf4 interleaved, kf1 replicated with decaying windows,
   complemented lanes) vs the reference permutation on random states.
3. Exactness of the multiply-shift constants (UseHint quotient, x mod q).
   Also the v4 constants (UseHint y = x - x div q, NTT bias bounds, Shoup).
4. Every vector of all three sets on the generated bytecode (Python EVM),
   v3 and v4; v2 and v3 are also pinned by SHA-256. v4 also: valid and
   flipped-message signatures at mu's block boundaries (mu blocks in the
   SIMD slot).
5. Forced rare paths, debug builds (not shipped): `dbg_force6` with
   OPT_DBG_NO_OVERLAY=1 squeezes the 6th RejNTTPoly block on every fix-up;
   verdicts must stay correct and the last group's 6th-block candidates must
   equal SHAKE128 bytes 840..1007.
"quick" skips 4 and 5.
"""
from __future__ import annotations

import hashlib
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import opt_evm  # noqa: E402
import opt_ref  # noqa: E402
from opt_asm import Asm  # noqa: E402
from opt_keccak import gen_keccak_f, rc_table, COMPLEMENTED, REP  # noqa: E402

VEC = {44: "vectors/calldata.txt", 65: "vectors/mldsa65/calldata.txt", 87: "vectors/mldsa87/calldata.txt"}
ROOT = os.path.join(HERE, "..")
Q = opt_ref.Q


def rows(nn):
    for line in open(os.path.join(ROOT, VEC[nn])):
        p = line.split()
        yield (b"" if p[0] == "-" else bytes.fromhex(p[0])), int(p[1])


def test_model():
    for nn in (44, 65, 87):
        n = 0
        for cd, exp in rows(nn):
            assert opt_ref.verify_model(nn, cd)[0] == exp, (nn, n)
            n += 1
        print(f"model: {nn} {n} vectors ok")


def test_keccak():
    ST, BT, RCT, KZ = 0, 0x320, 0x640, 0x940
    rng = random.Random(1)
    for scale, kz in ((4, None), (1, None), (1, KZ)):
        a = Asm()
        a.pushl("done")
        a.jump("kf")
        a.label("done")
        a.op("STOP")
        gen_keccak_f(a, "kf", ST, BT, RCT, 2, scale, kz_addr=kz)
        code = a.assemble()
        for _ in range(3):
            states = [[rng.getrandbits(64) for _ in range(25)] for _ in range(4 if scale == 4 else 1)]
            mem = bytearray(KZ + 25 * 32)
            for i in range(25):
                w = opt_ref.interleave([s[i] for s in states]) if scale == 4 else states[0][i] * REP
                if i in COMPLEMENTED:
                    w ^= opt_ref.M256
                mem[ST + 32 * i:ST + 32 * i + 32] = w.to_bytes(32, "big")
            for i, v in enumerate(rc_table(scale)):
                mem[RCT + 32 * i:RCT + 32 * i + 32] = v.to_bytes(32, "big")
            r = opt_evm.run(code, b"", memory=mem)
            out = [int.from_bytes(r["memory"][32 * i:32 * i + 32], "big") ^ (opt_ref.M256 if i in COMPLEMENTED else 0)
                   for i in range(25)]
            exp = [opt_ref.keccak_f(s) for s in states]
            if scale == 4:
                assert all(opt_ref.deinterleave(out[i]) == [e[i] for e in exp] for i in range(25))
            else:
                assert all(out[i] == exp[0][i] * REP for i in range(25))
        print(f"keccak: scale {scale}{' (v3, 3-round decay)' if kz else ''} ok, {r['gas_used']} gas per call")


def test_constants():
    M, K = 1074791297, 53
    # exact for x < 4.3e9; UseHint inputs are < 2^31
    for x in list(range(1 << 16)) + [j * Q + d for j in range(1, 513) for d in (-1, 0)] + \
            [random.Random(2).randrange(1 << 32) for _ in range(200000)]:
        assert (x * M) >> K == x // Q
    for d, (k, m) in {190464: (39, 2886403), 523776: (42, 8396809)}.items():
        g2 = d // 2
        for x in range(g2 - 1, Q + g2 - 1):
            assert (x * m) >> k == x // d
    for v in range(43, 89):
        assert v - 44 * (((v * 94) >> 12) & 3) == v % 44
    # v3 UseHint: D = (r + g2 - 1) div g2 by multiply-shift; the result
    # ((D >> 1) + m - h + 2 (h & D)) mod m equals FIPS 204 Algorithm 40
    for g2, (k, mm) in {95232: (38, 2886403), 261888: (42, 16793617)}.items():
        m = (Q - 1) // (2 * g2)
        for r in range(Q):
            D = ((r + g2 - 1) * mm) >> k
            assert D == (r + g2 - 1) // g2
            assert (D >> 1) % m == opt_ref.use_hint(0, r, g2)
            assert ((D >> 1) + m - 1 + 2 * (D & 1)) % m == opt_ref.use_hint(1, r, g2)
    # v4 UseHint: y = x - (x div q) for x < 2^31; D' = (y + g2 - 1) div g2 by
    # multiply-shift (exact for y + g2 - 1 < 2^31 + g2, checked at both ends of
    # every quotient interval, the product is monotone); D' = D + 2 m (x div q),
    # so the result equals Algorithm 40; v mod 44 exact for v < 2^15
    import gen_opt
    for g2, (k, mm) in gen_opt.Gen.DIVG2W.items():
        N = (1 << 31) + g2
        assert (N * mm) >> 64 == 0
        for qv in range(N // g2 + 1):
            for y in (qv * g2, min(qv * g2 + g2 - 1, N - 1)):
                assert (y * mm) >> k == qv
        m = (Q - 1) // (2 * g2)
        for x in list(range(0, 1 << 31, 4093)) + [j * Q + d for j in range(1, 257) for d in (-1, 0, 1)]:
            r = x % Q
            D = ((x - x // Q + g2 - 1) * mm) >> k
            assert (D >> 1) % m == opt_ref.use_hint(0, r, g2)
            assert ((D >> 1) + m - 1 + 2 * (D & 1)) % m == opt_ref.use_hint(1, r, g2)
    k44, m44 = gen_opt.Gen.MOD44W
    assert all(v - 44 * ((v * m44) >> k44) == v % 44 for v in range(1 << 15))
    # v4 forward NTT: inputs z + 8q (bias from the z decoder), b' = a - u without
    # +2q; u < t / 2^32 + q (Montgomery) or q (1 + b / 2^32) (Shoup, pass A).
    # Lanes stay in [0, 2^28) and Montgomery / Shoup inputs in range.
    from opt_ntt import Kernel
    rng = random.Random(3)
    for z in range(1, 8):
        zs = Kernel.shoup(z)
        for b in [0, 1, (1 << 28) - 1] + [rng.randrange(1 << 28) for _ in range(20000)]:
            u = b * opt_ref.ZETAS[z] - ((b * zs) >> 32) * Q
            assert 0 <= u < Q + (b * Q >> 32) + 1 and (u - b * opt_ref.ZETAS[z]) % Q == 0
    for nn in (44, 65, 87):
        p = opt_ref.derived(nn)
        lo, hi = p["g1"] + 9 * Q - (1 << p["zbits"]) + 1, p["g1"] + 9 * Q
        for layer in range(8):
            t = hi * (Q - 1)
            assert t < 1 << 64 and hi < 1 << 32
            umax = Q + (hi * Q >> 32) + 1 if layer < 3 else (t >> 32) + Q
            lo, hi = lo - umax, hi + umax
            assert lo >= 0 and hi < 1 << 28
    print("constants: multiply-shift quotients exact; v4 NTT bias bounds hold")


def run_vectors(nn, code, check6=None):
    import gen_opt
    bad = 0
    ext = 0
    for cd, exp in rows(nn):
        r = opt_evm.run(code, cd)
        got = int.from_bytes(r["ret"], "big") if r["status"] == "return" and len(r["ret"]) == 32 else None
        bad += got != exp
        if check6 and len(cd) >= check6.L.HDR:
            L, g = check6.L, check6
            m = r["memory"]
            W = lambda a: int.from_bytes(m[a:a + 32], "big")  # noqa: E731
            if W(L.MISC + 0x1E0):
                ext += 1
                for s, role in enumerate(g.schedule[-1]["slots"]):
                    if role and role[0] == "A":
                        stream = hashlib.shake_128(cd[:32] + bytes([role[2], role[1]])).digest(1008)
                        pos = [stream[3 * t] | stream[3 * t + 1] << 8 | (stream[3 * t + 2] & 0x7F) << 16
                               for t in range(280, 336)]
                        got6 = [(W(L.ABUF + 32 * t) >> (64 * s)) & opt_ref.M64 for t in range(280, 336)]
                        bad += got6 != pos
    return bad, ext


def test_bytecode(version, force6=False):
    import gen_opt
    sub = {"v3": (), "v4": ("v4",)}[version]
    for nn in (44, 65, 87):
        L = gen_opt.Layout(nn, version)
        g = gen_opt.Gen(L)
        if force6:
            g.dbg_force6 = True
        code = g.build()
        if not force6:
            with open(os.path.join(ROOT, "MlDsaOpt", str(nn), *sub, "opt.hex")) as f:
                assert f.read().strip() == code.hex(), f"MlDsaOpt {version} artifact is stale: run gen_opt.py"
        bad, ext = run_vectors(nn, code, g if force6 else None)
        assert bad == 0, (nn, bad)
        print(f"bytecode {version}{' (forced 6th squeeze)' if force6 else ''}: {nn} ok"
              + (f", {ext} vectors with 6th-block checks" if force6 else ""))


def test_mu_lengths(version="v4", build=None, run=None):
    """Message lengths around mu's block boundaries (66 + |M| = 136 k), the
    SIMD/kf1 switch (|M| = 613 / 614 for v4) and beyond: a valid signature
    (dilithium-py, fixed key) must verify and a one-bit message change must
    not, on every set. build(nn) -> code and run default to gen_opt and
    opt_evm.run."""
    import gen_opt
    sys.path.insert(0, os.path.join(ROOT, ".ref", "pylib"))
    from dilithium_py.ml_dsa import ML_DSA_44, ML_DSA_65, ML_DSA_87
    libs = {44: ML_DSA_44, 65: ML_DSA_65, 87: ML_DSA_87}
    lens = [69, 70, 205, 206, 341, 342, 477, 478, 613, 614, 749, 750, 1500]
    for nn in (44, 65, 87):
        code = build(nn) if build else gen_opt.Gen(gen_opt.Layout(nn, version)).build()
        pk, sk = libs[nn].key_derive(bytes(range(32)))
        for ml in lens:
            msg = bytes((7 * i + ml) & 0xFF for i in range(ml))
            sig = libs[nn].sign(sk, msg, deterministic=True)
            for m, exp in ((msg, 1), (msg[:-1] + bytes([msg[-1] ^ 0x80]), 0)):
                cd = pk + sig + m
                r = (run or opt_evm.run)(code, cd)
                assert int.from_bytes(r["ret"], "big") == exp, (version, nn, ml, exp)
        print(f"mu lengths {version}: {nn} ok ({len(lens)} lengths, valid and flipped)")


