#!/usr/bin/env python3
"""Generate MlDsaOptNN/Fn/Ginit/Lanes.lean: one block lemma per stored lane of `ginit`.

Usage (repo root): python3 MlDsaOpt65/Fn/Ginit/gen_lanes.py NN > MlDsaOptNN/Fn/Ginit/Lanes.lean
(NN = 65 or 87). Block costs are the static costs; the total must equal `Gas.ginit`
(printed on stderr). The entry pc is the start of the `ginit` region of
`MlDsaOpt/NN/layout.txt`, so the lemmas follow the current bytes."""
import re
import sys

NN = sys.argv[1]
with open(f"MlDsaOpt/{NN}/layout.txt") as f:
    ENTRY = int(re.search(r"^\s*(\d+) \.\.\s+\d+\s+\d+ bytes\s+ginit$", f.read(), re.M).group(1))

rows = []
with open(f"MlDsaOpt{NN}/listing.tsv") as f:
    next(f)
    for line in f:
        i, pc, ins = line.rstrip("\n").split("\t")
        rows.append((int(i), int(pc), ins))
start = next(k for k, r in enumerate(rows) if r[1] == ENTRY)


def cost(ins):
    op = ins.split()[0]
    if op == "JUMPDEST":
        return 1
    if op in ("PUSH0", "POP"):
        return 2
    if op.startswith("PUSH") or op.startswith("DUP") or op.startswith("SWAP"):
        return 3
    if op in ("NOT", "AND", "OR", "XOR", "MLOAD", "MSTORE", "ADD", "SUB", "SHL", "SHR"):
        return 3
    if op == "MUL":
        return 5
    if op == "JUMP":
        return 8
    raise ValueError(op)


blocks = []
cur = []
k = start
while True:
    i, pc, ins = rows[k]
    cur.append(rows[k])
    k += 1
    if ins == "MSTORE":
        blocks.append(cur)
        cur = []
    if ins == "JUMP":
        blocks[-1] = blocks[-1] + cur
        break
assert len(blocks) == 25, len(blocks)
total = sum(cost(r[2]) for b in blocks for r in b)
print(f"-- total {total}", file=sys.stderr)

STK0 = "wd l4 :: wd cmult :: wd amult :: wd keep :: wd ret :: tail"
STK = "wd (2 ^ 256 - 1 - keep) :: " + STK0
SW = "(storeWords m 0 (ginitWord m keep amult cmult l4) {n})"

out = []
out.append(f"""import MlDsaOpt{NN}.Fn.Group.Defs
import MlDsaOpt{NN}.Budget
import MlDsaOpt{NN}.Infra
import MlDsaOpt44.Fn.Sponge.Mem
import MlDsaOpt44.Fn.Sponge.Ginit
set_option warningAsError true
set_option maxHeartbeats 0
set_option linter.unusedSimpArgs false
set_option linter.unusedVariables false
/-!
# `ginit` (ML-DSA-{NN}): one block lemma per stored lane, chained (WP G1)

Generated by `python3 MlDsaOpt65/Fn/Ginit/gen_lanes.py {NN}` from `MlDsaOpt{NN}/listing.tsv` (template:
`MlDsaOpt44/Fn/Sponge/Ginit.lean`): the block of lane `x` ends with its `MSTORE`,
the last one with the returning `JUMP`; the memory after lane `x` is
`storeWords m 0 (ginitWord …) (x + 1)` (`KS = 0`).
-/

namespace MlDsaOpt{NN}.Proofs.G1

open MlDsaOpt44.Proofs MlDsaOpt44.Proofs.WP4

open EvmSemantics
open EvmSemantics.EVM
open MlDsaOptCommon
open MlDsaOpt{NN}.Proofs.Infra

theorem g1_spread_1f : spread 0x1F = 69905 := by unfold spread; decide +kernel

theorem g1_spread_top : spread 9223372036854775808 =
    7237005577332262213973186563042994240829374041602535252466099000494570602496 := by
  have h := padTop_eq; unfold padTop at h; exact h

set_option hygiene false in
/-- Close the value goal of a `ginit` lane block. -/
macro "ginit{NN}_value" : tactic => `(tactic| (
  have hkL : keep % 115792089237316195423570985008687907853269984665640564039457584007913129639936 = keep :=
    Nat.mod_eq_of_lt hk
  have hlL : l4 % 115792089237316195423570985008687907853269984665640564039457584007913129639936 = l4 :=
    Nat.mod_eq_of_lt hl
  have hnL : (115792089237316195423570985008687907853269984665640564039457584007913129639935 - keep) %
      115792089237316195423570985008687907853269984665640564039457584007913129639936 =
      115792089237316195423570985008687907853269984665640564039457584007913129639935 - keep :=
    Nat.mod_eq_of_lt (by omega)
  simp only [MlDsaOpt{NN}.Proofs.ginitWord, MlDsaOpt44.Proofs.complemented, MlDsaOpt{NN}.Proofs.RHO1,
    MlDsaOpt44.Proofs.KS, g1_spread_1f, g1_spread_top, List.mem_cons, List.mem_nil_iff,
    Nat.reduceMul, Nat.reduceAdd, Nat.reducePow, Nat.reduceSub, Nat.reduceLT, Nat.reduceEqDiff,
    or_false, or_true, false_or, if_true, if_false, Nat.lt_irrefl, ↓reduceIte,
    or_modL, xor_modL, and_modL, Nat.mod_mod, word_mod, hkL, hlL, hnL,
    Nat.xor_zero, Nat.zero_xor, Nat.zero_or, Nat.or_zero, Nat.zero_mod, Nat.mul_comm, Nat.xor_comm,
    Nat.xor_assoc, xor_left_comm', Nat.and_comm, Nat.or_comm]))
""")

pcs = []
for x, b in enumerate(blocks):
    pc0 = b[0][1]
    g = sum(cost(r[2]) for r in b)
    idx = ", ".join(str(r[0]) for r in b)
    last = x == 24
    pre = STK0 if x == 0 else STK
    src = f"(callState s {pc0} ({pre}) {SW.format(n=x)})"
    if last:
        dst = f"(callState s ret tail {SW.format(n=25)})"
    else:
        pc1 = blocks[x + 1][0][1]
        dst = f"(callState s {pc1} ({STK}) {SW.format(n=x+1)})"
    pcs.append((pc0, g))
    extra = "\n  have hret := hr.small\n  have hj := hr.jumpdest" if last else ""
    lemmas = "word_storeWords_out, hj" if last else "word_storeWords_out"
    out.append(f"""set_option maxRecDepth 100000 in
theorem ginit_lane{x} {{s : State}} (hs : Ctx s) {{ret : Nat}} {{tail : List UInt256}}
    (hr : RetOK Stack.ginit ret tail) (m : ByteArray) {{keep amult cmult l4 : Nat}}
    (hk : keep < 2 ^ 256) (hl : l4 < 2 ^ 256) :
    Reach {src}
      {dst} {g} := by
  have := hr.depth; simp only [Stack.ginit, Stack.leaf] at this
  have haw : s.activeWords.toNat ≤ 18446744073709551616 := hs.small
  have hsz := hs.sized; simp only [memWords] at hsz{extra}
  refine reach_block hs [{idx}] (by decide +kernel) ?_
  rw [storeWords_succ _ _ _ {x}]
  opt{NN}_block [{lemmas}]
  refine wb_congr ?_ (by norm_num); ginit{NN}_value
""")

chain = "(ginit_lane0 hs hr m hk hl)"
for x in range(1, 25):
    chain = f"({chain}.trans (ginit_lane{x} hs hr m hk hl))"
out.append(f"""theorem ginitWord_lt (m : ByteArray) {{keep amult cmult l4 : Nat}} (hk : keep < 2 ^ 256)
    (hl : l4 < 2 ^ 256) (x : Nat) : ginitWord m keep amult cmult l4 x < 2 ^ 256 := by
  have hw := word_lt m (KS + 32 * x)
  refine Nat.or_lt_two_pow ?_ (Nat.lt_of_le_of_lt Nat.and_le_left hw)
  repeat' apply Nat.xor_lt_two_pow
  all_goals (split <;> first | exact Nat.mod_lt _ (by norm_num) | omega)

theorem ginit_reach {{s : State}} (hs : Ctx s) {{ret : Nat}} {{tail : List UInt256}}
    (hr : RetOK Stack.ginit ret tail) (m : ByteArray) {{keep amult cmult l4 : Nat}}
    (hk : keep < 2 ^ 256) (hl : l4 < 2 ^ 256) :
    ∃ m', (∀ x, x < 25 → word m' (KS + 32 * x) = ginitWord m keep amult cmult l4 x) ∧
      FrameExcept m m' [(KS, KS + 800)] ∧
      Call s Entry.ginit [wd l4, wd cmult, wd amult, wd keep] ret tail m [] m' Gas.ginit := by
  refine ⟨storeWords m 0 (ginitWord m keep amult cmult l4) 25, fun x hx => ?_,
    storeWords_mono_frame (by simp [KS]) (by simp [KS]), ?_⟩
  · have := word_storeWords_get (m := m) (base := 0) (ginitWord_lt (amult := amult) (cmult := cmult) m hk hl x) hx
    simpa [KS] using this
  · rw [call_iff, Entry.ginit, Gas.ginit]
    exact {chain}

end MlDsaOpt{NN}.Proofs.G1
""")
sys.stdout.write("\n".join(out))
