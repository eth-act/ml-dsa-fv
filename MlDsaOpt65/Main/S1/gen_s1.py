#!/usr/bin/env python3
"""WP S1 generator: `seg_init`, `seg_tbl`, `seg_rho`, `seg_fin` block files for
ML-DSA-65 and ML-DSA-87 (adapted from `MlDsaOpt44/Main/Wp11Gen/gen_{init,tbl,rho,fin}.py`).

  python3 MlDsaOpt65/Main/S1/gen_s1.py

writes `MlDsaOptNN/Main/S1/{Tac,Init,Tbl,Rho,FinBlocks}.lean` (`FinBlocks`: `gen_s1_fin.py`) for NN = 65, 87. Instruction
indices, pcs and block costs are read from `MlDsaOptNN/listing.tsv`; the pure
lemmas (tables, byte swaps, sponge facts) are the ML-DSA-44 ones.
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
N256 = 2 ** 256
M8 = int('ff00' * 15 + 'ff', 16); M16 = int('ffff0000' * 7 + 'ffff', 16)
M32 = int('ffffffff00000000' * 3 + 'ffffffff', 16)
M64 = 2 ** 64 - 1; REP = 1 + 2 ** 64 + 2 ** 128 + 2 ** 192

# per set: memWords, HDR, TOP - 32, segment pcs
CFG = {
    65: dict(mw=2833, hdr=5261, sz=0x16200, tbl=(1110, 3093, 'Inv1', 'Inv2'),
             rho=(3115, 3565, 'Inv3', 'Inv4'), fin=6688, FIN=0x14900, CTOFF=1952, nblk=6),
    87: dict(mw=2865, hdr=7219, sz=0x16600, tbl=(1135, 3118, 'Inv2', 'Inv3'),
             rho=(3140, 3389, 'Inv4', 'Inv5'), fin=6724, FIN=0x14900, CTOFF=2592, nblk=8),
}


class Listing:
    def __init__(self, nn):
        self.rows = [l.rstrip('\n').split('\t')
                     for l in open(os.path.join(ROOT, f'MlDsaOpt{nn}', 'listing.tsv'))][1:]
        self.idx = {int(r[1]): int(r[0]) for r in self.rows}

    def pc(self, i):
        return int(self.rows[i][1])

    def op(self, i):
        return self.rows[i][2]

    def c(self, i):
        op = self.rows[i][2].split()[0]
        if op == 'PUSH0':
            return 2
        if op.startswith('PUSH') or op.startswith('DUP') or op.startswith('SWAP'):
            return 3
        t = {'JUMPDEST': 1, 'MUL': 5, 'JUMP': 8, 'JUMPI': 10, 'POP': 2, 'CALLDATASIZE': 2, 'ADDRESS': 2}
        if op in t:
            return t[op]
        if op == 'RETURN':
            return 0
        if op in ('AND', 'OR', 'XOR', 'NOT', 'LT', 'GT', 'EQ', 'ISZERO', 'SHL', 'SHR', 'ADD', 'SUB',
                  'MLOAD', 'MSTORE', 'CALLDATALOAD', 'BYTE'):
            return 3
        raise Exception(op)

    def cost(self, a, b):
        """Cost of the instructions with pcs in [a, b)."""
        return sum(self.c(i) for i in range(self.idx[a], self.idx[b]))

    def L(self, a, b):
        return ', '.join(str(i) for i in range(self.idx[a], self.idx[b]))

    def Lx(self, a, b):
        return ', '.join(str(i) for i in range(self.idx[a], self.idx[b] + 1))


def header(nn, imports, doc):
    imp = '\n'.join(f'import {m}' for m in imports)
    return f'''{imp}
set_option warningAsError true
set_option maxHeartbeats 0
/-! {doc}

Generated by `MlDsaOpt65/Main/S1/gen_s1.py` (WP S1); do not edit. -/

namespace MlDsaOpt{nn}.Proofs.S1

open EvmSemantics
open EvmSemantics.EVM
open MlDsaOptCommon
open MlDsa
open MlDsaOpt{nn}.Proofs.Infra
'''


def gen_tac(nn):
    shared = 'KS KB RC4 RC1 MISC NNEG CNT HAVE6 TBL CW ABUF FL ZH TT'.split()
    own = 'ZH2 BASES IDX ACC HP FIN RHO1 CB TRL MU BK SP TOP KZ'.split()
    names = ', '.join([f'MlDsaOpt44.Proofs.{c}' for c in shared] + [f'MlDsaOpt{nn}.Proofs.{c}' for c in own])
    return f'''import MlDsaOpt{nn}.Main.Base
set_option warningAsError true
/-! `s1_avoids{nn}`: close `Avoids rs lo hi` for literal ML-DSA-{nn} layout ranges (fully
qualified constants: the ML-DSA-44 `avoids_tac` is in scope wherever the 44 lemma
modules are imported, and the two macros share their syntax).

Generated by `MlDsaOpt65/Main/S1/gen_s1.py` (WP S1); do not edit. -/

macro "s1_avoids{nn}" : tactic => `(tactic| (
  simp only [MlDsaOptCommon.avoids_cons, MlDsaOptCommon.avoids_nil, and_true,
    {names}]
  omega))
'''


def pre(nn):
    return f'''  have haw : s.activeWords.toNat ≤ 18446744073709551616 := hs.small
  have hfw : {CFG[nn]["mw"]} ≤ s.activeWords.toNat := hs.sized
'''


# ---------------------------------------------------------------- init
def gen_init(nn):
    X = Listing(nn); cf = CFG[nn]
    L = lambda a, b: ', '.join(str(i) for i in range(a, b))
    rcw = int(X.op(80).split()[1], 16)
    src = header(nn, [f'MlDsaOpt{nn}.Main.S1.Tac', 'MlDsaOpt44.Main.Init.Blocks'],
                 '# Segment `0 … 992`: size check, memory sizing, the `RC4`/`RC1` iota tables (straight line).')
    src += f'''open MlDsaOpt44.Proofs (rc4v rc1v rc4v_eq rc1v_eq rcv_lt byteAt_ntb0)

/-- Memory after the sizing store. -/
@[irreducible] def initM0 : ByteArray :=
  MachineState.writeBytes .empty (Data.Bytes.natToBytesPadded 0 32) {cf["sz"]}

/-- Memory at `992`. -/
@[irreducible] def initMem : ByteArray := storeWords (storeWords initM0 RC4 rc4v 24) RC1 rc1v 24

theorem init_run {{s : State}} (h0 : Ctx0 s) (haw : s.activeWords.toNat = 0)
    (hcd : {cf["hdr"]} ≤ s.executionEnv.calldata.size) (hfit : s.executionEnv.calldata.size < 2 ^ 64) :
    EvmProof.Stepper.runLocatedBlock (Artifact.locatedPath [{L(0, 8)}]) (callState s 0 [] .empty) =
      some (callState (sized s) 15 [] initM0) := by
  have hr : (callState s 0 [] .empty).halt = .Running := h0.running
  simp only [sized, memWords, initM0]
  opt{nn}_block [Ctx0.code, Ctx0.running, haw, MachineState.activeWordsAfter]
  rfl

theorem init_rc4 {{s : State}} (hs : Ctx s) (M : ByteArray) :
    Reach (callState s 15 [] M) (callState s 664 [] (storeWords M RC4 rc4v 24)) 216 := by
{pre(nn)}  opt{nn}_reach [{L(8, 80)}]
  rfl

theorem init_rc1a {{s : State}} (hs : Ctx s) (M : ByteArray) :
    Reach (callState s 664 [] M) (callState s {X.pc(141)} [wd {rcw}] (storeWords M RC1 rc1v 12)) 207 := by
{pre(nn)}  opt{nn}_reach [{L(80, 141)}]
  rfl

theorem init_rc1b {{s : State}} (hs : Ctx s) (M : ByteArray) :
    Reach (callState s {X.pc(141)} [wd {rcw}] (storeWords M RC1 rc1v 12))
      (callState s 992 [] (storeWords M RC1 rc1v 24)) 206 := by
{pre(nn)}  opt{nn}_reach [{L(141, 202)}]
  rfl

theorem initMem_frame : FrameExcept initM0 initMem [(RC4, RC4 + 768), (RC1, RC1 + 768)] := by
  unfold initMem
  exact (FrameExcept.storeWords initM0 RC4 rc4v 24).trans (FrameExcept.storeWords _ RC1 rc1v 24)

theorem sized_aw (s : State) (pc : Nat) (stk : List UInt256) (m : ByteArray) :
    (callState (sized s) pc stk m).activeWords.toNat = memWords := sized_activeWords s

theorem callState_aw (s : State) (pc : Nat) (stk : List UInt256) (m : ByteArray) :
    (callState s pc stk m).activeWords = s.activeWords := rfl

theorem initM0_zero : ZeroOn initM0 MISC TOP := by
  intro a h1 h2
  unfold initM0
  rw [byteAt_writeBytes, natToBytesPadded_size]
  split
  · exact byteAt_ntb0 (by omega)
  · unfold byteAt; rw [dif_neg (by simp)]

theorem inv0_initMem : Inv0 initMem where
  rc4 := fun i hi => by
    unfold initMem
    rw [FrameExcept.word (FrameExcept.storeWords _ RC1 rc1v 24) (by s1_avoids{nn}),
      word_storeWords (rcv_lt i hi).1 24 hi, rc4v_eq i hi]
  rc1 := fun i hi => by
    unfold initMem
    rw [word_storeWords (rcv_lt i hi).2 24 hi, rc1v_eq i hi]
  zero := ZeroOn.frame initM0_zero initMem_frame (by s1_avoids{nn})

theorem seg_init_proof {{s : State}} (h0 : Ctx0 s) (haw : s.activeWords.toNat = 0)
    (hcd : HDR ≤ s.executionEnv.calldata.size) (hfit : s.executionEnv.calldata.size < 2 ^ 64) :
    ∃ m, Inv0 m ∧
      Reach (callState s 0 [] .empty) (callState (sized s) 992 [] m)
        (Gas.pInit + MachineState.memCost memWords) := by
  have hs : Ctx (sized s) := sized_ctx h0 hfit
  have hA := reach_block_pot (h0.callState 0 [] .empty) [{L(0, 8)}] (cost := {X.cost(0, 15)})
    (by decide +kernel) (init_run h0 haw (by unfold HDR at hcd; exact hcd) hfit)
  have hm1 := sized_aw s 15 [] initM0
  have hm0 := (congrArg UInt256.toNat (callState_aw s 0 [] .empty)).trans haw
  rw [hm1, hm0] at hA
  refine ⟨initMem, inv0_initMem, ?_⟩
  rw [show initMem = storeWords (storeWords initM0 RC4 rc4v 24) RC1 rc1v 24 by unfold initMem; rfl]
  have h := ((hA.trans (init_rc4 hs _)).trans (init_rc1a hs _)).trans (init_rc1b hs _)
  refine h.mono ?_
  have : MachineState.memCost 0 = 0 := rfl
  unfold Gas.pInit
  omega

end MlDsaOpt{nn}.Proofs.S1
'''
    assert X.cost(15, 664) == 216 and X.cost(664, X.pc(141)) == 207 and X.cost(X.pc(141), 992) == 206
    return src


