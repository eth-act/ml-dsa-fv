#!/usr/bin/env python3
"""Generate Rows.lean, Blocks1.lean, Blocks2.lean and RoundSpec.lean for keccakF.

Run from the repository root: `python3 MlDsa44/Proofs/Fn/Keccak/gen_keccak.py`
(needs `lake env lean` for the block costs; set TMPDIR as for `lake`)."""
import os, re, subprocess, sys, tempfile

yul = open('MlDsa44/Reference/reference.yul').read().split('\n')[20:228]
listing = {}
for line in open('docs/reference.listing'):
    i, pc, ins = line.rstrip('\n').split('\t')
    listing[int(i)] = (int(pc), ins)

# rows: list of (dst, [(addr, j, n)]) in program order (10 rows)
rows = []
cur = None
for l in yul:
    m = re.match(r'\s*let b(\d) := xor\(mload\((0x[0-9a-f]+)\), d(\d)\)', l)
    if m:
        k = int(m.group(1))
        if k == 0:
            cur = {'b': [None] * 5, 'dst': None}
            rows.append(cur)
        cur['b'][k] = [int(m.group(2), 16), int(m.group(3)), 0]
        continue
    m = re.match(r'\s*b(\d) := or\(and\(shl\((\d+), b\d\)', l)
    if m:
        cur['b'][int(m.group(1))][2] = int(m.group(2))
        continue
    m = re.match(r'\s*mstore\((0x[0-9a-f]+), xor\(b0, and\(not\(b1\), b2\)\)\)', l)
    if m and cur is not None and cur['dst'] is None:
        cur['dst'] = int(m.group(1), 16)
assert len(rows) == 10, len(rows)

def bexpr(b):
    a, j, n = b
    x = f"(UInt256.xor (mloadY M {a}) d{j})"
    return x if n == 0 else f"(rotY {x} {n})"

out = []
P = out.append
P("""import MlDsa44.Proofs.Fn.Keccak.Model
/-! Generated by `gen_keccak.py`: the row stores of the two rounds. -/

namespace MlDsa44.Proofs.KeccakModel

open EvmSemantics
open EvmSemantics.EVM
""")
for idx, row in enumerate(rows):
    rnd, y = idx // 5 + 1, idx % 5
    bs = ' '.join(bexpr(b) for b in row['b'])
    P(f"/-- Round {rnd}, output row {y}. -/")
    P(f"def row{rnd}_{y} (M : ByteArray) (d0 d1 d2 d3 d4 : UInt256) : ByteArray :=")
    P(f"  chi5Y M {row['dst']} {bs}")
    P("")
DS = "(dY M1 0x6c0 0x660) (dY M1 0x640 0x680) (dY M1 0x660 0x6a0) (dY M1 0x680 0x6c0) (dY M1 0x6a0 0x640)"
for rnd, src in ((1, 0), (2, 0x320)):
    P(f"/-- Theta and the five row stores of round {rnd} (before iota). -/")
    P(f"def half{rnd} (M : ByteArray) : ByteArray :=")
    P(f"  let M1 := thetaY M {src}")
    t = "M1"
    for y in range(5):
        t = f"(row{rnd}_{y} {t} {DS})"
    P(f"  {t[1:-1]}")
    P("")
P("""/-- One iteration of the `keccakF` loop (two rounds). -/
def iterY (M : ByteArray) (r : Nat) : ByteArray :=
  iotaY (half2 (iotaY (half1 M) 0x320 (rcAddr1 r))) 0 (rcAddr2 r)
""")
P("end MlDsa44.Proofs.KeccakModel")
open('MlDsa44/Proofs/Fn/Keccak/Rows.lean', 'w').write('\n'.join(out) + '\n')

# blocks
blocks = {
    1: [('theta', 4, 90), ('d', 91, 170), ('row', 171, 279), ('row', 280, 399), ('row', 400, 519),
        ('row', 520, 639), ('row', 640, 764)],
    2: [('iotaTheta', 765, 855), ('d', 856, 935), ('row', 936, 1044), ('row', 1045, 1164),
        ('row', 1165, 1284), ('row', 1285, 1404), ('row', 1405, 1529), ('iotaLoop', 1530, 1549)],
}
costs_needed = []
for rnd in blocks:
    for (_, a, b) in blocks[rnd]:
        costs_needed.append((a, b))
costs_needed += [(2, 3), (-1, -1)]
# cost evaluation through Lean
lean = ["import MlDsa44.Proofs.Infra"]
for (a, b) in costs_needed:
    path = list(range(a, b + 1)) if a >= 0 else list(range(4, 11)) + [1550, 1551, 1552]
    lean.append(f"#eval MlDsa44.Proofs.Infra.blockCostEval {path}")
fd, tmp = tempfile.mkstemp(suffix='.lean')
with os.fdopen(fd, 'w') as f:
    f.write('\n'.join(lean) + '\n')
res = subprocess.run(['lake', 'env', 'lean', tmp], capture_output=True, text=True)
os.remove(tmp)
vals = [int(x) for x in res.stdout.split()]
cost = {k: v for k, v in zip(costs_needed, vals)}
print('costs', cost, file=sys.stderr)

HDR = """import MlDsa44.Proofs.Fn.Keccak.Rows
import MlDsa44.Proofs.Infra.Reflect
/-! Generated by `gen_keccak.py`: straight-line blocks of round {rnd}. -/

namespace MlDsa44.Proofs.KeccakBlocks

open EvmSemantics
open EvmSemantics.EVM
open MlDsa44.Proofs.KeccakModel

set_option maxRecDepth 100000
set_option maxHeartbeats 0
"""
CTX = ("{s : State} (hs : Ctx s) {ret : Nat} {tail : List UInt256} (htl : tail.length ≤ 960)\n"
       "    (haw : s.activeWords.toNat ≤ 18446744073709551616) (hsz : 2535 ≤ s.activeWords.toNat)")
DST = "d4 :: d3 :: d2 :: d1 :: d0 :: wd r :: wd ret :: tail"
DIDS = "(d0 d1 d2 d3 d4 : UInt256)"
DYS = ("dY M 0x6a0 0x640 :: dY M 0x680 0x6c0 :: dY M 0x660 0x6a0 :: dY M 0x640 0x680 :: "
       "dY M 0x6c0 0x660 :: wd r :: wd ret :: tail")

def pc(i):
    return listing[i][0]

for rnd in blocks:
    o = [HDR.format(rnd=rnd)]
    y = 0
    for (kind, a, b) in blocks[rnd]:
        path = list(range(a, b + 1))
        c = cost[(a, b)]
        p0, p1 = pc(a), pc(b + 1)
        extra = "rotY, chiY, chi5Y, xor5Y, mloadY, mstoreY"
        if kind == 'theta':
            name = f"blk_theta{rnd}"
            args = f"(M : ByteArray) (r : Nat) (hr : r < 24)"
            pre = "wd r :: wd ret :: tail"; post = pre
            memo = "(thetaY M 0)"
            extra = "thetaY, xor5Y, mloadY, mstoreY"
        elif kind == 'd':
            name = f"blk_d{rnd}"
            args = "(M : ByteArray) (r : Nat)"
            pre = "wd r :: wd ret :: tail"; post = DYS; memo = "M"
            extra = "dY, rotY, mloadY"
        elif kind == 'row':
            name = f"blk_row{rnd}_{y}"
            args = f"(M : ByteArray) (r : Nat) {DIDS}"
            pre = DST
            post = DST if y < 4 else "wd r :: wd ret :: tail"
            memo = f"(row{rnd}_{y} M d0 d1 d2 d3 d4)"
            extra = f"row{rnd}_{y}, " + extra
            y += 1
        elif kind == 'iotaTheta':
            name = f"blk_iotaTheta{rnd}"
            args = "(M : ByteArray) (r : Nat) (hr : r < 24)"
            pre = "wd r :: wd ret :: tail"; post = pre
            memo = "(thetaY (iotaY M 0x320 (rcAddr1 r)) 0x320)"
            extra = "thetaY, iotaY, rcAddr1, xor5Y, mloadY, mstoreY"
        elif kind == 'iotaLoop':
            name = f"blk_iotaLoop"
            args = "(M : ByteArray) (r : Nat) (hr : r < 24)"
            pre = "wd r :: wd ret :: tail"; post = "wd (r + 2) :: wd ret :: tail"
            memo = "(iotaY M 0 (rcAddr2 r))"
            p1 = 6
            extra = "iotaY, rcAddr2, mloadY, mstoreY"
        o.append(f"theorem {name} {CTX}\n    {args} :\n"
                 f"    Infra.Reach (callState s {p0} ({pre}) M)\n"
                 f"      (callState s {p1} ({post}) {memo}) {c} := by\n"
                 f"  {'evm_reach' if rnd == 1 and kind == 'theta' else 'evm_rreach'} {path}\n    with [{extra}]\n")
    o.append("end MlDsa44.Proofs.KeccakBlocks")
    open(f'MlDsa44/Proofs/Fn/Keccak/Blocks{rnd}.lean', 'w').write('\n'.join(o) + '\n')
print(cost[(2, 3)], cost[(-1, -1)], sum(cost[(a, b)] for r in blocks for (_, a, b) in blocks[r]), file=sys.stderr)

# Round specification file
xs = ' '.join(f'x{k}' for k in range(25))
arr = '#[' + ', '.join(f'x{k}' for k in range(25)) + ']'
o = ["""import MlDsa44.Proofs.Fn.Keccak.Rows
import MlDsa44.Proofs.Fn.Keccak.Bridge
/-! Generated by `gen_keccak.py`: one round of the Yul model computes
`Crypto.Keccak.round` on the lanes. -/

namespace MlDsa44.Proofs.KeccakModel

open EvmSemantics
open EvmSemantics.EVM

set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option linter.unusedSimpArgs false
"""]
conj = ' ∧\n    '.join(f'mloadY m (base + {32*k}) = L x{k}' for k in range(25))
o.append(f"""theorem lanesAt_of {{m : ByteArray}} {{base : Nat}} {{{xs} : UInt64}}
    (h : {conj}) :
    LanesAt m base {arr} := by
  refine ⟨rfl, fun i hi => ?_⟩
  obtain ⟨{', '.join(f'h{k}' for k in range(25))}⟩ := h
  interval_cases i
""" + ''.join(f"  · exact word_of_mloadY h{k}\n" for k in range(25)))
elems = ', '.join(f'A[{k}]!' for k in range(25))
o.append(f"""theorem arr25 {{A : Array UInt64}} (h : A.size = 25) : A = #[{elems}] := by
  rcases A with ⟨l⟩
  simp only [List.size_toArray] at h
  match l, h with
  | [{xs.replace(' ', ', ')}], _ => rfl
""")
o.append("""theorem iotaY_eq {M : ByteArray} {dst : Nat} {rcA : UInt256} {rc : UInt64}
    (h : mloadY M rcA.toNat = L rc) :
    iotaY M dst rcA = mstoreY M dst (UInt256.xor (mloadY M dst) (L rc)) := by
  rw [iotaY, h]
""")
ROUND_SIMPS = """Crypto.Keccak.round, Std.Legacy.Range.forIn_eq_forIn_range', Std.Legacy.Range.size,
      List.forIn_pure_yield_eq_foldl, Id.run_pure, pure_bind, bind_pure_comp, Id.run_bind, List.range',
      List.foldl, Id.run_map, Nat.reduceAdd, Nat.reduceMul, Nat.reduceMod, Nat.reduceSub, Nat.reduceDiv,
      Array.replicate, List.replicate, Nat.add_zero, Nat.zero_add, map_pure, Array.set!_eq_setIfInBounds,
      List.setIfInBounds_toArray, List.set_cons_succ, List.set_cons_zero, List.getElem!_toArray,
      List.getElem!_cons_succ, List.getElem!_cons_zero, Crypto.Keccak.rotOff, List.forIn_cons,
      List.forIn_nil"""
for rnd, src, dst in ((1, 0, 0x320), (2, 0x320, 0)):
    hyps = '\n    '.join(f'(h{k} : mloadY M {src + 32*k} = L x{k})' for k in range(25))
    rows_ = ', '.join(f'row{rnd}_{y}' for y in range(5))
    hs_ = ', '.join(f'h{k}' for k in range(25))
    o.append(f"""theorem round{rnd}_spec (M : ByteArray) (rcA : UInt256) (rc : UInt64) {{{xs} : UInt64}}
    {hyps}
    (hrc : mloadY (half{rnd} M) rcA.toNat = L rc) :
    LanesAt (iotaY (half{rnd} M) {dst} rcA) {dst} (Crypto.Keccak.round {arr} rc) := by
  rw [iotaY_eq hrc]
  simp only [{ROUND_SIMPS}]
  apply lanesAt_of
  simp only [half{rnd}, {rows_}, chi5Y, chiY, thetaY, xor5Y, dY, mloadY_mstoreY_same,
    mloadY_mstoreY_ne, {hs_}, L_xor, L_andnot, L_rotl, rotl64_zero, Nat.reduceAdd, Nat.reduceLeDiff,
    Nat.reduceLT, or_true, true_or, and_self, and_true, Nat.add_zero]
""")
o.append("end MlDsa44.Proofs.KeccakModel")
open('MlDsa44/Proofs/Fn/Keccak/RoundSpec.lean', 'w').write('\n'.join(o) + '\n')
